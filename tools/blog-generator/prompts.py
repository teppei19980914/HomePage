"""NewtonX アシスタントに送る記事生成プロンプトの組み立て。

CLAUDE.md のブログ運用ルールをここに集約する。ルールを変えたい場合は
このファイルを直接編集すればよい（コード側のロジック変更は不要）。
"""

from __future__ import annotations

from newtonx_gen import END_MARKER

STYLE_NOTE = """\
文体の参考（このサイトの既存記事の書き出し例。表現をそのまま真似る必要はないが、
一人称・敬体（です/ます）で、体験に基づく一人称エッセイ調にすること）:

- 「エンジニアにとって大切なことは何でしょうか。2021年に新卒でIT業界に入り、
  業務経験だけでなく職務経歴書には書かれないようなことも含めていろいろな経験を
  してきた今、私にとっての答えは大切にしていることです。」
- 「私はこれまで、相手への配慮や場の安定を大切にしたいと思ってきました。」

見出しは Markdown の `##`（H2）のみを使用し、`#`（H1）は使わないこと
（frontmatter の title が実質的な H1 のため、本文で重複させない）。
"""


def build_prompt(
    draft_text: str,
    ja_catalog: str,
    en_catalog: str,
    date_hint: str,
) -> str:
    return f"""\
あなたは技術者向け個人ブログのライティングアシスタントです。以下の「たたき台」を元に、
日本語版・英語版の2つのブログ記事を作成してください。出力は必ず1つのJSONオブジェクトのみとし、
説明文やコードフェンス以外の余計なテキストは含めないでください。

# たたき台

{draft_text}

# 厳守ルール

1. **frontmatter は出力しない**。title / description / tags / body は JSON の別フィールドとして返す。
   date とファイル名（YYYYMMDD-slug）はアプリ側で自動的に決めるので出力不要。
   （参考: 今回使う予定の日付は {date_hint} だが、本文中に日付を書く必要はない）
2. ja は Single Source of Truth。en は ja の内容を過不足なく伝える独立した記事として書く
   （直訳ではなく、英語話者に自然な文章にする）。
3. title: 30〜60文字（日本語・英語とも文字数でカウント）。主要キーワードを含み、
   クリックしたくなる具体的な表現にする。
4. description: 120〜160文字。主要+副次キーワードを含み、記事の価値が伝わる一文にする。
5. tags: 5個。"AI"や"エンジニア"のような汎用語だけでなく、固有名詞・具体的なテーマを含める。
6. body:
   - Markdown。見出しは `##` のみ（`#` は使わない。frontmatter title と重複するため）。
   - 日本語版は概ね1800〜2400文字（読了時間3〜5分の目安。日本語400字÷500字/分で計算）。
     英語版は概ね700〜900語（200語/分換算で3〜5分）。
   - 冒頭は直接的な問いかけや自分の立場の提示から始める。
   - 本文中に **内部リンクを3件以上** 含める。リンク先は下記「既存記事一覧」に実在する
     stem のみを使うこと（存在しないURLを創作しない）。リンク形式:
     - 日本語: `[記事タイトル](/HomePage/ja/blog/{{stem}}/)`
     - 英語: `[Article Title](/HomePage/en/blog/{{stem}}/)`
   - 本文の最後に、日本語なら `## 関連記事`、英語なら `## Related Articles` という
     見出しで、使った内部リンクを箇条書きでまとめる（各行に短い説明を添える）。
   - 裸のURL（`https://...` を直接貼るだけ）は禁止。外部情報を引用する場合、
     正確なURLが分からないなら **リンクにせずテキストのみで言及する**（URLを創作しない）。
   - 具体的な金額・連絡先・第三者を特定できる情報は書かない。
   - 長文になる場合、出力の最後に必ず `{END_MARKER}` を付ける。

{STYLE_NOTE}

# 既存記事一覧（日本語版・内部リンク候補）

{ja_catalog}

# 既存記事一覧（英語版・内部リンク候補）

{en_catalog}

# 出力形式（この JSON 構造のみを出力すること）

```json
{{
  "slug_suggestion": "english-kebab-case-slug",
  "ja": {{
    "title": "...",
    "description": "...",
    "tags": ["...", "...", "...", "...", "..."],
    "body": "## 見出し\\n\\n本文..."
  }},
  "en": {{
    "title": "...",
    "description": "...",
    "tags": ["...", "...", "...", "...", "..."],
    "body": "## Heading\\n\\nBody..."
  }}
}}
```
"""
